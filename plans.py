# ---------------------------------------------------------------- پلن آی‌پی ثابت (فقط آلمان)
# {حجم به گیگ: قیمت} — شروع از ۱۵۰ گیگ، نامحدود از نظر زمان
STATIC_PLANS: dict[int, int] = {
    150: 950_000,
    200: 1_250_000,  # ⚠️ پیش‌فرض — ویرایش کنید
    300: 1_800_000,  # ⚠️ پیش‌فرض — ویرایش کنید
}

# ---------------------------------------------------------------- متن‌های توضیحی
NORMAL_COUNTRIES = "🇩🇪 آلمان | 🇬🇧 انگلیس | 🇮🇷 ایران | 🇹🇷 ترکیه"
NORMAL_NOTE = (
    "📦 پلن‌های معمولی شامل هر چهار کشور 🇩🇪 آلمان، 🇬🇧 انگلیس، 🇮🇷 ایران و 🇹🇷 ترکیه "
    "در یک کانفیگ هستند و نیازی به انتخاب کشور نیست."
)
STATIC_NOTE = "پلن آی‌پی ثابت فقط برای سرور آلمان موجود است، نامحدود است و از ۱۵۰ گیگ شروع می‌شود."


@dataclass(frozen=True)
class Plan:
    code: str  # کدی که در callback_data می‌رود، مثل n:30:5
    label: str  # عنوان کامل پلن
    category: str  # 'normal' | 'static_ip'
    duration: str  # مدت (برای ذخیره در دیتابیس)
    price: int  # قیمت به تومان
    extra: str  # توضیح اضافه برای صفحه پرداخت


def get_plan(code: str) -> Plan | None:
    """از روی کد پلن، مشخصات و قیمت واقعی را برمی‌گرداند (None اگر نامعتبر باشد)."""
    parts = code.split(":")
    try:
        if parts[0] == "n" and len(parts) == 3:
            group = NORMAL_PLANS[parts[1]]
            value = int(parts[2])
            price = group["items"][value]
            if group["kind"] == "volume":
                label = f"پلن معمولی | {group['title']} | {value} گیگ"
                duration = f"{parts[1]} days"
            else:
                label = f"پلن معمولی | نامحدود | {value} روزه"
                duration = f"unlimited {value} days"
            return Plan(code, label, "normal", duration, price, f"🌍 کشورها: {NORMAL_COUNTRIES}")
        if parts[0] == "s" and len(parts) == 2:
            gb = int(parts[1])
            price = STATIC_PLANS[gb]
            return Plan(
                code,
                f"پلن آی‌پی ثابت 🇩🇪 | نامحدود | {gb} گیگ",
                "static_ip",
                "unlimited",
                price,
                "🇩🇪 سرور: آلمان (آی‌پی ثابت)",
            )
    except (KeyError, ValueError, IndexError, TypeError):
        return None
    return None
